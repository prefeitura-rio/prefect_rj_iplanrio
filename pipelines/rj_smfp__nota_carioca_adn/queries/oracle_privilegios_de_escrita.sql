SELECT privilege AS privilegio
FROM session_privs
WHERE privilege IN (
  'INSERT ANY TABLE', 'UPDATE ANY TABLE', 'DELETE ANY TABLE', 'ALTER ANY TABLE', 'DROP ANY TABLE',
  'CREATE ANY TABLE', 'CREATE TABLE', 'CREATE PROCEDURE', 'EXECUTE ANY PROCEDURE', 'ALTER SYSTEM', 'ALTER USER',
  'GRANT ANY PRIVILEGE', 'GRANT ANY OBJECT PRIVILEGE', 'SELECT ANY TABLE'
)
UNION ALL
SELECT privilege || ' ON ' || table_name AS privilegio
FROM all_tab_privs_recd
WHERE owner = '$schema'
  AND table_name IN ('MV_DOCUMENTOSFISCAISNACIONAIS', 'MV_DOCUMENTOSFISCAISNACIONAIS_QUARENTENA')
  AND privilege NOT IN ('SELECT', 'READ')
